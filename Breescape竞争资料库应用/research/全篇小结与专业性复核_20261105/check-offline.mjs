import { chromium } from '/Users/voidengine/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';
import fs from 'node:fs/promises';
import { fileURLToPath,pathToFileURL } from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
const work=fileURLToPath(new URL('.',import.meta.url));
const delivery=JSON.parse(await fs.readFile(work+'delivery.json','utf8'));
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({offline:true,viewport:{width:1440,height:1050}});
const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(pathToFileURL(delivery.html).href);await page.waitForSelector('.brand-report');
await page.evaluate(async()=>{for(const i of document.images)i.loading='eager';await Promise.all([...document.images].map(i=>i.decode()));});
assert.equal(await page.locator('.report-section').count(),6);
assert.equal(await page.locator('.report-stale').count(),0);
const media=await page.evaluate(()=>[...document.images].map(i=>({ok:i.complete&&i.naturalWidth>0,src:i.src.slice(0,26)})));
assert.ok(media.length>0&&media.every(i=>i.ok));
const allLinks=await page.locator('a[href]').evaluateAll(es=>es.map(e=>e.getAttribute('href')));
const relative=allLinks.filter(h=>!/^([a-z]+:|#|\/)/i.test(h));
for (const href of new Set(relative))await fs.access(path.join(delivery.folder,decodeURIComponent(href)));
const hasReview=page.locator('#report-section-2 a[href="#review-proof-718"]').first();
await hasReview.click();assert.equal(await page.locator('#review-proof-718').getAttribute('open'),'');
assert.ok((await page.locator('#review-proof-718').innerText()).includes('I will continue to use these due to the comfort'));
const allText=await page.locator('.brand-report').innerText();
assert.ok(!allText.includes('升级期待帮助试购'));assert.ok(!allText.includes('阶段性解释：，'));
await page.locator('#report-section-2').scrollIntoViewIfNeeded();
await page.evaluate(()=>window.scrollTo(0,scrollY+document.querySelector('#report-section-2').getBoundingClientRect().top-28));
await page.screenshot({path:work+'qa-offline-section-2.png'});
await page.setViewportSize({width:390,height:844});
const mobile=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));assert.ok(mobile.scroll<=mobile.width+1);
assert.deepEqual(errors,[]);
await fs.writeFile(work+'qa-offline.json',JSON.stringify({sections:6,images:media.length,imagesLoaded:media.every(i=>i.ok),relativeLinks:relative.length,uniqueRelativeLinks:new Set(relative).size,review718:true,mobile,errors},null,2));
console.log(JSON.stringify({sections:6,images:media.length,relativeLinks:relative.length,review718:true,mobile,errors}));
await browser.close();
